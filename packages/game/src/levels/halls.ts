import type { LevelDef, LevelProp, Point, PropKind } from '../types.ts'
import { HALL_BASE } from './hall-base.ts'

/** Зал из общей основы: свои — id, название, оформление, ковёр и препятствия */
function hall(
  id: string,
  name: string,
  theme: string,
  pathPoints: Point[],
  cells: Point[],
  kinds: PropKind[],
): LevelDef {
  const props: LevelProp[] = cells.map((cell, i) => ({ kind: kinds[i], cell }))
  return { ...HALL_BASE, id, name, theme, pathPoints, props }
}

